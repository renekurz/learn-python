# Subscripting
print("Hello"[0]) # -> you will get the "H" because it's the first letter and in programming the first one is always 0

# String
print("123" + "345") # -> you will get "123345" because these are strings who will be concatenated

# Integer
print(123 + 345) # -> you will get the calculated sum of 123 + 345

# Large Integer
print(123_456_789) # -> you will get "123456789" because the computer removes the "_" but for you it's easier to read

# Float -> because it has a decimal point
print(3.14159)

# Boolean -> only True or False
print(True)
print(False)