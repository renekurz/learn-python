print(123 + 456)    # -> sum
print(7 - 3)        # -> minus
print(3 * 2)        # -> multiplication
print(5 / 3)        # -> division (Float)
print(5 // 3)       # -> division (Integer) - watch out, because it's only removing the decimal places
print(2 ** 3)       # -> 2 * 2 * 2

# PEMDAS (KlaPuStri)
print(3 * 3 + 3 / 3 - 3)    # Output: 7.0
print(3 * (3 + 3) / 3 - 3)  # Output: 3.0