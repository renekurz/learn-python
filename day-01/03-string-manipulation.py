# \n -> new Line
print("Hello world!\nHello world!")

#  + -> Concat Strings
print("Hello" + "Angela")

# 3 Methods how you can get a space between
# 1. Enter a space after "Hello"
print("Hello " + "Angela")

# 2. Enter a space before "Angela"
print("Hello" + " Angela")

# 3. Enter a third string in between with only a space
print("Hello" + " " + "Angela")